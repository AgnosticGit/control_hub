#!/usr/bin/env node
// Build the Rust engine for the browser:
//   1. cargo build (wasm32, profile wasm-release)
//   2. wasm-bindgen --target web -> packages/web-engine/pkg (JS glue + .wasm)
//   3. copy the .wasm to apps/web/public/wasm/<name>.<sha256-16>.wasm and write
//      apps/web/src/generated/wasm-manifest.ts so the JS glue bundled by Next.js
//      and the fetched .wasm always come from the same build (content-hashed URL,
//      safe to cache immutably).
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { root, run } from "./lib.mjs";

const REQUIRED_BINDGEN = "0.2.129";

async function bindgenVersion() {
  const { execFileSync } = await import("node:child_process");
  try {
    return execFileSync("wasm-bindgen", ["--version"], { encoding: "utf8" }).trim().split(/\s+/)[1];
  } catch {
    return null;
  }
}

const v = await bindgenVersion();
if (v !== REQUIRED_BINDGEN) {
  console.error(
    `wasm-bindgen CLI ${REQUIRED_BINDGEN} is required (found: ${v ?? "none"}).\n` +
      `Install: cargo install wasm-bindgen-cli --version ${REQUIRED_BINDGEN} --locked`,
  );
  process.exit(1);
}

await run("cargo", [
  "build",
  "-p",
  "controlhub-web-engine",
  "--target",
  "wasm32-unknown-unknown",
  "--profile",
  "wasm-release",
]);

const pkg = join(root, "packages", "web-engine", "pkg");
rmSync(pkg, { recursive: true, force: true });
await run("wasm-bindgen", [
  "--target",
  "web",
  "--out-dir",
  pkg,
  "--out-name",
  "controlhub_engine",
  join(root, "target", "wasm32-unknown-unknown", "wasm-release", "controlhub_web_engine.wasm"),
]);

const wasmPath = join(pkg, "controlhub_engine_bg.wasm");
const bytes = readFileSync(wasmPath);
const sha256 = createHash("sha256").update(bytes).digest("hex");
const fileName = `controlhub_engine.${sha256.slice(0, 16)}.wasm`;

const publicDir = join(root, "apps", "web", "public", "wasm");
mkdirSync(publicDir, { recursive: true });
for (const f of readdirSync(publicDir)) {
  if (f.endsWith(".wasm")) rmSync(join(publicDir, f));
}
copyFileSync(wasmPath, join(publicDir, fileName));

const genDir = join(root, "apps", "web", "src", "generated");
mkdirSync(genDir, { recursive: true });
writeFileSync(
  join(genDir, "wasm-manifest.ts"),
  `// Generated by scripts/build-wasm.mjs. Do not edit.
export const WASM_URL = "/wasm/${fileName}";
export const WASM_SHA256 = "${sha256}";
export const WASM_BYTES = ${bytes.length};
`,
);
console.error(`[wasm] ${fileName} (${(bytes.length / 1024).toFixed(0)} KiB)`);
